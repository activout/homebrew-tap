"""Regenerate Formula/*.rb from each CLI's latest GitHub release. Run by .github/workflows/update.yml."""
import json
import os
import urllib.request

# (Homebrew os, Homebrew arch) -> the release's (os, arch) names
# Intel Macs are not supported: Apple stopped selling them in 2023 and macOS 26 is their last release.
GO = {("macos", "arm"): ("darwin", "arm64"),
      ("linux", "arm"): ("linux", "arm64"), ("linux", "intel"): ("linux", "amd64")}
DOTNET = {("macos", "arm"): ("osx", "arm64"), ("linux", "intel"): ("linux", "x64")}

CLIS = [
    dict(cmd="elg", repo="activout/elg", license="MIT", platforms=GO, sums="checksums.txt",
         asset="elg_{tag}_{os}_{arch}.tar.gz", test="version",
         desc="Unofficial CLI for GleSYS email hosting, DNS and servers"),
    dict(cmd="nordray-tunnel", repo="activout/nordray-tunnel", license="Apache-2.0", platforms=GO, sums="SHA256SUMS",
         asset="nordray-tunnel_{tag}_{os}_{arch}", test="version",
         desc="Self-hosted HTTP tunnels in your own Bunny account"),
    dict(cmd="blue5", repo="activout/Activout.Blue5", license="MIT", platforms=DOTNET, sums="SHA256SUMS",
         asset="blue5-{os}-{arch}.tar.gz", test="--version",
         desc="Unofficial read-only CLI for the Bluestone PIM Public API"),
    dict(cmd="content-scheduler", repo="activout/Activout.C9.Scheduler", license="MIT", platforms=DOTNET,
         sums="SHA256SUMS", asset="content-scheduler-{os}-{arch}.tar.gz", test="--help",
         desc="Reconcile cron-based publish rules into Contentful Scheduled Actions"),
    dict(cmd="bank", repo="activout/Activout.Banking", license="MIT", platforms=DOTNET, sums="SHA256SUMS",
         asset="bank-{os}-{arch}.tar.gz", test="--version",
         desc="Archive and export your own bank transactions via Enable Banking"),
]


def get(url):
    headers = {"Accept": "application/vnd.github+json"}
    if token := os.environ.get("GITHUB_TOKEN"):
        headers["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers)) as r:
        return r.read().decode()


def formula(c):
    release = json.loads(get(f"https://api.github.com/repos/{c['repo']}/releases/latest"))
    tag = release["tag_name"]
    assets = {a["name"]: a["browser_download_url"] for a in release["assets"]}
    if c["sums"] not in assets:
        return None
    sums = dict(reversed(line.split()) for line in get(assets[c["sums"]]).splitlines() if line.strip())

    blocks = {}
    for (brew_os, brew_arch), (os_, arch) in c["platforms"].items():
        name = c["asset"].format(tag=tag, os=os_, arch=arch)
        if name not in assets or name not in sums:
            return None  # this release has no binaries yet: keep the previous formula
        blocks.setdefault(brew_os, []).append(
            f'    on_{brew_arch} do\n      url "{assets[name]}"\n      sha256 "{sums[name]}"\n    end')

    body = ""
    for brew_os, arch_blocks in blocks.items():
        only = "" if len(arch_blocks) > 1 else \
            f"    depends_on arch: :{'arm64' if 'on_arm' in arch_blocks[0] else 'x86_64'}\n"
        body += f"  on_{brew_os} do\n{only}" + "\n".join(arch_blocks) + "\n  end\n\n"
    depends = "" if "macos" in blocks and "linux" in blocks else \
        f"  depends_on :{'macos' if 'macos' in blocks else 'linux'}\n\n"

    raw = not c["asset"].endswith(".tar.gz")
    install = f'Dir["{c["cmd"]}_*"].first => "{c["cmd"]}"' if raw else f'"{c["cmd"]}"'
    klass = "".join(part.capitalize() for part in c["cmd"].split("-"))
    return f'''# Generated by update.py from {c["repo"]}'s latest release. Do not edit by hand.
class {klass} < Formula
  desc "{c["desc"]}"
  homepage "https://github.com/{c["repo"]}"
  version "{tag.removeprefix("v")}"
  license "{c["license"]}"

{depends}{body}  def install
    bin.install {install}
  end

  test do
    system bin/"{c["cmd"]}", "{c["test"]}"
  end
end
'''


os.makedirs("Formula", exist_ok=True)
for c in CLIS:
    if text := formula(c):
        path = f"Formula/{c['cmd']}.rb"
        if not os.path.exists(path) or open(path).read() != text:
            open(path, "w").write(text)
            print(f"updated {path}")
